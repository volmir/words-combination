#!/usr/bin/env python3
"""Offline notices from resolved Gradle artifacts and their cached Maven POMs.

Run :app:exportRuntimeLicenseInputs first. No network, no license inference
from a library name. Unknown POM licenses fail closed.
"""
import argparse
import hashlib
import io
import json
import os
from pathlib import Path
import xml.etree.ElementTree as ET
import zipfile

ROOT = Path(__file__).resolve().parents[1]
NS = {'m': 'http://maven.apache.org/POM/4.0.0'}


def digest(content):
    return hashlib.sha256(content).hexdigest()


def pom_licenses(cache, coordinate, seen=()):
    if coordinate in seen:
        raise ValueError('Cyclic Maven parent')
    paths = sorted(cache.joinpath(*coordinate.split(':')).glob('*/*.pom'))
    if len(paths) != 1:
        raise ValueError('Missing/ambiguous cached POM: ' + coordinate)
    raw = paths[0].read_bytes()
    root = ET.fromstring(raw)
    licenses = [dict(name=l.findtext('m:name', namespaces=NS), url=l.findtext('m:url', namespaces=NS))
                for l in root.findall('m:licenses/m:license', NS)]
    evidence = [dict(artifact=coordinate, sha256=digest(raw))]
    if not licenses:
        parent = root.find('m:parent', NS)
        if parent is None:
            raise ValueError('No declared license: ' + coordinate)
        parent_id = ':'.join(parent.findtext('m:' + k, namespaces=NS)
                             for k in ('groupId', 'artifactId', 'version'))
        licenses, inherited = pom_licenses(cache, parent_id, (*seen, coordinate))
        evidence += inherited
    for license in licenses:
        url = license['url'] or ''
        if 'apache.org/licenses/LICENSE-2.0' in url:
            license['spdx'] = 'Apache-2.0'
        elif url == 'https://opensource.org/licenses/BSD-3-Clause':
            license['spdx'] = 'BSD-3-Clause'
        else:
            raise ValueError('Unreviewed license: ' + repr(license))
    return licenses, evidence


def archive_notices(raw, prefix=''):
    result = []
    with zipfile.ZipFile(io.BytesIO(raw)) as archive:
        for name in sorted(archive.namelist()):
            if name.endswith('/'):
                continue
            data = archive.read(name)
            if name.lower().endswith('.jar'):
                result += archive_notices(data, prefix + name + '!')
            elif any(k in Path(name).name.lower() for k in ('license', 'notice', 'copying')):
                result.append((prefix + name, data.decode('utf-8')))
    return result


def generate(inputs, cache, legal):
    profiles = json.loads(inputs.read_text())
    artifacts = {}
    texts = {}
    for profile, rows in sorted(profiles.items()):
        for row in rows:
            coordinate = row['artifact']
            if coordinate not in artifacts:
                licenses, evidence = pom_licenses(cache, coordinate)
                artifacts[coordinate] = dict(artifact=coordinate, profiles=[], licenses=licenses,
                                             pom_evidence=evidence, files=[])
            entry = artifacts[coordinate]
            if profile not in entry['profiles']:
                entry['profiles'].append(profile)
            path = Path(row['file'])
            raw = path.read_bytes()
            record = dict(name=path.name, sha256=digest(raw), embedded_notices=[])
            for name, text in archive_notices(raw):
                key = digest(text.encode())
                texts[key] = text
                record['embedded_notices'].append(dict(path=name, sha256=key))
            if record not in entry['files']:
                entry['files'].append(record)
    inventory = sorted(artifacts.values(), key=lambda r: r['artifact'])
    lines = ['Resolved runtime libraries (debug/release; R8 may remove unused code).',
             'Generated by tools/build_library_notices.py from cached Maven POMs and actual AAR/JAR files.',
             'Exact coordinates, profiles, artifact/POM/embedded notice SHA-256: RUNTIME_LIBRARIES.json.', '']
    for r in inventory:
        lines.append(r['artifact'] + ' [' + ', '.join(r['profiles']) + '] — ' +
                     ', '.join(l['spdx'] for l in r['licenses']))
    lines += ['', 'Apache-2.0 full text:', (legal / 'Apache-2.0.txt').read_text(),
              '', 'Protobuf BSD-3-Clause upstream notice:',
              'Source: https://raw.githubusercontent.com/protocolbuffers/protobuf/v3.25.1/LICENSE',
              'DataStore POM declares BSD-3-Clause. Exact repackaged protobuf revision remains unverified;',
              'this upstream notice is retained conservatively and is not proof of that revision.',
              (legal / 'Protobuf-BSD-3-Clause.txt').read_text()]
    for key, value in sorted(texts.items()):
        lines += ['', 'Verbatim embedded third-party notice SHA-256 ' + key + ':', value]
    lines += ['', 'End of runtime library notices.']
    notice = '\n'.join(lines)
    if not notice.endswith('\n'):
        notice += '\n'
    return {'RUNTIME_LIBRARIES.json': json.dumps(inventory, ensure_ascii=False, indent=2) + '\n',
            'LIBRARY_NOTICES.txt': notice}


def default_gradle_cache():
    gradle_home = os.environ.get('GRADLE_USER_HOME')
    base = Path(gradle_home) if gradle_home else Path.home() / '.gradle'
    return base / 'caches/modules-2/files-2.1'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--inputs', type=Path, default=ROOT / 'app/build/reports/licenses/runtime-inputs.json')
    parser.add_argument('--cache', type=Path, default=default_gradle_cache())
    parser.add_argument('--legal', type=Path, default=ROOT / 'legal')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    outputs = generate(args.inputs, args.cache, args.legal)
    for name, content in outputs.items():
        path = args.legal / name
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise ValueError('Stale runtime notice: ' + name)
        else:
            path.write_text(content, encoding='utf-8')
    print('Runtime notices: ' + ('verified' if args.check else 'generated'))


if __name__ == '__main__':
    main()
