package com.example.sostavslova.data

/**
 * Неизменяемый порядок поставленной кампании v1. Не брать из текущего levels.json:
 * после обновления на устройстве уже будут новые данные, включая перестановки и замены.
 * Источник: data/levels.json, SHA-256
 * e4ded7a9bdfc5855c69bd167abb03c25d5291652a1504956d3a0e99e4742e73a.
 * Для миграции нужны только исходные слова и их позиции, не старые задания/пороги.
 */
internal object LegacyCampaignV1 {
    private val words = listOf(
        "рекуперация", "опровержение", "хлопкопункт", "аспирантура", "ратификация",
        "чемпионство", "велосипед", "субъективизм", "взвешивание", "окаменелость",
        "демонстрация", "артикуляция", "фисгармоника", "переливание", "сурдоперевод",
        "колядование", "селитроварня", "субординация", "реввоенсовет", "правоведение",
        "одноколейка", "аккумулятор", "магнитофон", "переводчица", "питекантроп",
        "вегетарианец", "регулировщик", "видеотехника", "мелодичность", "пудлинговка",
    )

    fun contains(word: String): Boolean = word in words

    /** v1 открывала следующий уровень только по completed предшественника. */
    fun highestUnlocked(completedWords: Set<String>): Int = words.indices
        .filter { words[it] in completedWords }
        .maxOfOrNull { (it + 2).coerceAtMost(words.size) } ?: 1
}
